import { chmodSync, existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { configDir } from "./config.ts";

export function shimPath(): string {
  return join(configDir(), "hook.sh");
}

// What each host expects on stdout when mac-sounds can't be found at all (unlinked,
// upgraded away, `bun unlink`'d) -- hardcoded here rather than read from the host
// adapters, because the entire point of this table is to work when the rest of the app
// is gone. Claude and Codex are silent on both the happy path and this degraded one;
// only Antigravity requires a decision field, since an absent one there would otherwise
// read as "block the stop" rather than "let the agent stop normally".
const FALLBACK_STDOUT_BY_HOST: Readonly<Record<string, string>> = {
  antigravity: '{"decision":"stop"}',
};

function generateShimScript(): string {
  // Captured now, at generation time, not re-resolved later inside the shell script:
  // Bun.main follows the mac-sounds symlink chain (`bun link` -> ~/.bun/bin/mac-sounds ->
  // this repo's src/index.ts) all the way to its real file, and process.execPath is the
  // literal bun binary currently executing this process. Both are absolute and both are
  // independent of whatever PATH a host's hook subprocess happens to inherit -- which is
  // the entire reason this shim exists (see the header comment baked into the script).
  const bunBin = process.execPath;
  const appEntry = Bun.main;
  const fallbackCases = Object.entries(FALLBACK_STDOUT_BY_HOST)
    .map(([host, stdout]) => `    ${host}) printf '%s' '${stdout}' ;;`)
    .join("\n");

  return `#!/usr/bin/env bash
# Generated by mac-sounds. Safe to delete -- reinstalling hooks recreates it. Do not
# hand-edit; the next install silently overwrites this file.
#
# Every host config points at this one script instead of at "mac-sounds" directly, for
# two reasons:
#  1. Hook subprocesses spawned by Claude Code / Codex / Antigravity CLI do not reliably
#     inherit a PATH containing ~/.bun/bin (or wherever \`bun link\` put the mac-sounds
#     symlink), so a host config must reference an absolute path -- and this script, plus
#     the absolute bun/app paths baked in below, is that absolute path.
#  2. If mac-sounds is ever unlinked, upgraded, or moved, this script must degrade
#     gracefully -- print exactly what the calling host expects on stdout and exit 0 --
#     rather than error out from inside the user's agent loop.
#
# Invocation contract: "$0" <hostId> <eventId> [ignored extra args...]
# stdin is forwarded to mac-sounds untouched (hosts deliver hook payloads there); the
# \`exec\` calls below replace this process rather than spawning a child, so open file
# descriptors -- stdin included -- pass through for free. Trailing args beyond $1/$2 are
# dropped on purpose (Codex appends a JSON payload as one more argv element).

BUN_BIN="${bunBin}"
APP_ENTRY="${appEntry}"
HOST="$1"
EVENT="$2"

if [ -x "$BUN_BIN" ] && [ -f "$APP_ENTRY" ]; then
  exec "$BUN_BIN" "$APP_ENTRY" hook "$HOST" "$EVENT"
fi

# Primary path gone (moved, upgraded, uninstalled) -- fall back to however mac-sounds is
# reachable on this shell's own PATH right now.
FALLBACK_APP="$(command -v mac-sounds 2>/dev/null)"
if [ -n "$FALLBACK_APP" ]; then
  exec "$FALLBACK_APP" hook "$HOST" "$EVENT"
fi

# mac-sounds is gone and not on PATH either. Some of these events are live control signals
# (Claude's Stop/SubagentStop, Antigravity's Stop) -- print exactly what each host expects
# when nothing runs, so "the app disappeared" reads as "let the agent stop normally", never
# as a block.
case "$HOST" in
${fallbackCases}
    *) ;;
esac
exit 0
`;
}

export function writeShim(): string {
  const dir = configDir();
  mkdirSync(dir, { recursive: true });

  const path = shimPath();
  const script = generateShimScript();
  // Same atomic-write idiom as config.ts's saveConfig(): a host can invoke this script at
  // any moment, independent of when writeShim() last ran, so the full content is written
  // to a same-directory temp file (same filesystem, so the following rename is atomic
  // under POSIX) and renamed over the target -- a concurrent reader only ever sees the
  // fully-old or fully-new script, never a half-written, unrunnable one.
  const tmpPath = join(dir, `.hook.sh.${process.pid}.${Date.now()}.tmp`);
  writeFileSync(tmpPath, script, "utf8");
  chmodSync(tmpPath, 0o755);
  renameSync(tmpPath, path);
  return path;
}

export function shimIsCurrent(): boolean {
  if (!existsSync(shimPath())) return false;
  try {
    return readFileSync(shimPath(), "utf8") === generateShimScript();
  } catch {
    // Unreadable for some reason (permissions, race with a delete) -- treat as "not
    // current" so the caller regenerates it rather than throwing.
    return false;
  }
}
